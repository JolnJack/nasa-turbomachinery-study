      IF(.NOT.IEEE_IS_FINITE(AL1)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(B4)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(BL1)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(BL4)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(PDSGN)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(U3)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(U4U3)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(R)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(V1)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(DELV)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(VMAX)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(XK)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(WD)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(ZZ)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(PD)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(ETAD)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(DELY)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(YMAX)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(D2)) GO TO 902
      IF(MODE.LT.0.OR.MODE.GT.5) GO TO 902
      IF(G.LE.1..OR.P0.LE.0..OR.T0.LE.0..OR.R.LE.0.) GO TO 902
      IF(MIN(A0,A1,A3,A5,D2,D3,U3,ZZ).LE.0.) GO TO 902
      IF(BL1.LE.0..OR.BL1.GT.1.) GO TO 902
      IF(BL4.LE.0..OR.BL4.GT.1.) GO TO 902
      IF(U4U3.LE.0..OR.U4U3.GE.1.) GO TO 902
      IF(ABS(AL1).GE.90..OR.ABS(B4).GE.90.) GO TO 902
      IF(V1.LE.0..OR.VMAX.LT.V1.OR.DELV.LE.0.) GO TO 902

   82 W4WC4= Y
      PW4= SUBR(Y,G)
      P4P4ID=YGIV/PW4
      PWC4 =PVCR*PD*PWVC3*PW4PW3*P4P4ID
   85 CONTINUE
      WUWC4=W4WC4*SINB4
      WXWC4=W4WC4*COSB4

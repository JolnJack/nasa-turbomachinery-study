      IF(ABS((V0VC0-X)/V1VC1).LT.TOL) GO TO 13
      GO TO 12
   13 VUVC1=V1VC1*SINAL1
      VRVC1=V1VC1*COSAL1
      VUVC2=VUVC1
C               STATOR EXIT CONDITIONS
C
      Q=PV1*COSAL1 *BL1
      X=V1VC1/3.
   61 F=(1.-G3*(X*X+VUVC2**2))**(1./G2)*X-Q
      F1=(F+Q)/X
      FP=-2.*X*X/G1*F1**(1./G2-1.)+F1
      X1=X-F/FP
      IF(ABS((X1-X)/X1)-TOL) 62,62,63
   63 X=X1
      GO TO 61
   62 VRVC2=X
      V2VC2=SQRT(VRVC2**2+VUVC2**2)
      PV2=SUBR(V2VC2,G)
      COSAL2=VRVC2/V2VC2
      AL2=ACOS(COSAL2)
      SINAL2=SIN(AL2)
C               FREE STREAM SPACE CONDITIONS
C
      VUVC3=VUVC2*D2/D3
      Q= PV2*COSAL2*D2/D3
      X=VUVC3/5.
   22 F=(1.-G3*(X*X+VUVC3**2))**(1./G2)*X-Q
      F1=(F+Q)/X
      FP=-2.*X*X/G1*F1**(1./G2-1.)+F1
      X1=X-F/FP
      IF(ABS((X1-X)/X1)-TOL) 20,20,21
   21 X=X1
      GO TO 22
   20 V3VC3=SQRT(VUVC3**2+X*X)
      COSAL3=X/V3VC3
      AL3=ACOS(COSAL3)
      SINAL3=SIN(AL3)
      VRVC3=X
C               ROTOR INLET CONDITIONS
C
      T3T3=(1.0-G3*(2.0*U3*VUVC3/VCR-(U3/VCR)**2))
      WCVC3=SQRT(T3T3)
      WUVC3=VUVC3-U3/VCR
      WUWC3=WUVC3/WCVC3
      W3VC3=SQRT(WUVC3**2+VRVC3**2)
      W3WC3=W3VC3/WCVC3
      WRWC3=SQRT(W3WC3**2-WUWC3**2)
      P3P3=T3T3**(G5)
      PWVC3=T3T3**(G1/2./G2)
      SINB3=WUWC3/W3WC3
      B3=ASIN(SINB3)
      COSB3=COS(B3)
      V3TU3=1.-1.98/ZZ
      VU3T=V3TU3*U3
      WU3T=VU3T-U3
      AB=ATAN((WU3T/VCR)/VRVC3)
      XI3=B3-AB
      FS =SIN(XI3)
      FC =COS(XI3)
      WCR3=WCVC3*VCR
      T4T3=1.-G3*(U3/WCR3)**2*(1.-U4U3**2)
      WC4WC3=SQRT(T4T3)
      W3WC4=W3WC3/WC4WC3
      PW4PW3=T4T3**(1./G3/2.)

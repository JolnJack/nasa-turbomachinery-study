      IF(MODE.EQ.0.OR.MODE.EQ.3) GO TO 46
      IF(MODE.EQ.1.OR.MODE.EQ.4) GO TO 48
      WRITE(6,509) PD,XK,WD
      IF(ITEST.EQ.1) WRITE(6,525) ETAD,PDSGN
      IF(ITEST.EQ.2) WRITE(6,526) ETAD,PDSGN
   46 CONTINUE
      WRITE(6,500)V1VC1,AL1,V3VC3,W4WC4,W5WC5,VUVC1,AL2,VUVC3,WUWC4,
     1WXWC5,VRVC1,AL3,VRVC3,WXWC4,V5VC5,V0VC0,B3,W3WC3,B4,VUVC5,V2VC2,
     2XI3,WUWC3,B5,VXVC5,VRVC2,VCR,WRWC3,VCR5,AL5
      WRITE(6,501)WTHODE,EQPRS,Z1,WTOP,W1,DHTCR,ETAS,XNU,DELHOT,DELH,
     1XNOTH,ETAT,XNS,XNOT,ELAM,EQTOR,EQPRT,Z,TOP,TOR,XN,P,WNODE,T5,P5
      IF(MODE.EQ.2.OR.MODE.EQ.5) GO TO 51
   48 CONTINUE
      IF(WXWC4.EQ.1.) GO TO 59

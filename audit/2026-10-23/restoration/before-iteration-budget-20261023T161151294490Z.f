C         A FORTRAN IV COMPUTER PROGRAM TO PREDICT DESIGN AND OFF
C         DESIGN PERFORMANCE OF A RADIAL INFLOW TURBINE
C
C                 INTERNATIONAL SYSTEM OF UNITS
C         MODE=0, IMPLIES OFF-DESIGN PERFORMANCE MODE WITH FULL OUTPUT.
C         MODE=1, IMPLIES OFF-DESIGN PERFORMANCE MODE WITH SHORT OUTPUT.
C         MODE=2, IMPLIES DESIGN MODE TO DETERMINE THE VALUE OF K AND PD.
C
C                 U. S. CUSTOMARY UNITS
C         MODE=3, IMPLIES OFF-DESIGN PERFORMANCE MODE WITH FULL OUTPUT.
C         MODE=4, IMPLIES OFF-DESIGN PERFORMANCE MODE WITH SHORT OUTPUT.
C         MODE=5, IMPLIES DESIGN MODE TO DETERMINE THE VALUE OF K AND PD.

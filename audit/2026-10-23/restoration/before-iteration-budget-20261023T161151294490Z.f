        IF(PD.LE.0..OR.PD.GT.1..OR.XK.LT.0.) GO TO 902
      ENDIF
      WRITE(6,200)NAME,CASE
      WRITE(6,400)G,P0,A1,AL1,B4,PD,R,T0,A3,BL1,BL4,XK,D3,A0,A5,U3,
     1U4U3,ZZ
      IF(MODE.EQ.1.OR.MODE.EQ.4) WRITE(6,666)
      DELV1= DELV
      ALX=AL1
      B4X=B4
      T=.01745329
      TOL=.00001
      AL1=T*AL1
      B4=T*B4
      COSAL1=COS(AL1)
      SINAL1=SIN(AL1)
      COSB4=COS(B4)
      SINB4=SIN(B4)

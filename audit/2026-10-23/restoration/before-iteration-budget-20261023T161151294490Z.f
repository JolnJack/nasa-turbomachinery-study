      SUBR(X,G)=(1.-(G-1.)/(G+1.)*X*X)**(1./(G-1.))*X
    1 READ(5,100,END=900,ERR=901) (NAME(I),I=1,10)
      READ(5,100,END=901,ERR=901) (CASE(I),I=1,10)
      CALL READ_NAMELIST_CARDS(5,'in',CARDS,IOS)
      IF(IOS.NE.0) GO TO 901
      READ(CARDS,IN,IOSTAT=IOS)

      IF(.NOT.IEEE_IS_FINITE(G)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(P0)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(T0)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(A0)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(A1)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(A3)) GO TO 902
      IF(.NOT.IEEE_IS_FINITE(A5)) GO TO 902

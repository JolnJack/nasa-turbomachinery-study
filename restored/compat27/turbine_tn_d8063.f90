IF(ABS(VALUE).GE.1..AND.ABS(VALUE).LT.1.E5) THEN
WRITE(FIELD,'(G13.6)') VALUE
ELSE
WRITE(FIELD,'(G13.5)') VALUE
ENDIF
END FUNCTION

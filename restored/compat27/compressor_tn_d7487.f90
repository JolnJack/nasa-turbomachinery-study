SUBROUTINE LININT (X1,Y1,X,Y,TN,MX,MY,F)
REAL QBIT
DIMENSION X(MX), Y(MY), TN(MX,MY)
DO 1 J3=2,MX
1 IF((X1.LE.QBIT(X(J3)))) GO TO 2
J3=MX
2 DO 3 J4=2,MY
3 IF((Y1.LE.QBIT(Y(J4)))) GO TO 4
J4=MY
4 J1=(J3-1)
J2=(J4-1)
EPS1=QBIT(QBIT((QBIT((X1-QBIT(X(J1))))/QBIT((QBIT(X(J3))-QBIT(X(J1)))))))
EPS2=QBIT(QBIT((QBIT((Y1-QBIT(Y(J2))))/QBIT((QBIT(Y(J4))-QBIT(Y(J2)))))))
EPS3=QBIT(QBIT((QBIT(1.0D0)-EPS1)))
EPS4=QBIT(QBIT((QBIT(1.0D0)-EPS2)))
F=QBIT(QBIT((QBIT((QBIT((QBIT((QBIT((QBIT(TN(J1,J2))*EPS3))*EPS4))+QBIT((QBIT((QBIT(TN(J3,J2))*EPS1))*EPS4))))+QBIT((QBIT((QBIT(TN(J1,J4))*EPS2))*EPS3))))+QBIT((QBIT((QBIT(TN(J3,J4))*EPS1))*EPS2)))))
RETURN
END
SUBROUTINE FNTGRL(NO,DELTAR,F,S)
REAL QBIT
DIMENSION F(20),S(20)
S(1)=QBIT(QBIT(0.0D0))
S(2)=QBIT(QBIT((QBIT((DELTAR*QBIT((QBIT((QBIT((QBIT(5.0D0)*QBIT(F(1))))+QBIT((QBIT(8.0D0)*QBIT(F(2))))))-QBIT(F(3))))))/QBIT(12.0D0))))
DO 1 I=3,NO
1 S(I)=QBIT(QBIT((QBIT(S((I-1)))+QBIT((QBIT((DELTAR*QBIT((QBIT((QBIT((QBIT(5.0D0)*QBIT(F(I))))+QBIT((QBIT(8.0D0)*QBIT(F((I-1)))))))-QBIT(F((I-2)))))))/QBIT(12.0D0))))))
RETURN
END
FUNCTION ARSIN(X)
REAL QBIT
ARSIN=QBIT(QBIT(ASIN(X)))
RETURN
END
FUNCTION QBIT(VALUE) RESULT(Q)
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
REAL VALUE,Q
IF(.NOT.IEEE_IS_FINITE(VALUE)) THEN
Q=VALUE
ELSE IF(VALUE.EQ.0.) THEN
Q=VALUE
ELSE
Q=SCALE(AINT(SCALE(FRACTION(VALUE),27)),EXPONENT(VALUE)-27)
ENDIF
END FUNCTION
